plt.ylabel('Count')
plt.show()

# Plot distribution of 'goals_scored_last_4y'
plt.figure(figsize=(8, 5))
sns.histplot(df['goals_scored_last_4y'], kde=True)
plt.title('Distribution of Goals Scored Last 4 Years')
